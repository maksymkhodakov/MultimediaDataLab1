def gtzan_analysis(gz, e, best, by_track):
    A = e["A"]
    out = []
    gains = [x["track_acc"] - x["seg_acc"] for x in gz["experiments"]]
    out.append(
        f"Базова мережа без аугментації (варіант A) правильно класифікує "
        f"{f3(A['seg_acc'])} 3-секундних фрагментів і {f3(A['track_acc'])} треків. "
        "В усіх варіантах голосування фрагментів підвищує точність на "
        f"{100 * min(gains):.0f}–{100 * max(gains):.0f} в. п.: окремі 3 секунди можуть "
        "бути «нетиповими» для жанру (вступ, пауза, соло одного інструмента), а "
        "усереднення по всьому треку згладжує такі випадкові помилки."
    )
    others = [x for x in gz["experiments"] if x["key"] != "A"]
    for x in others:
        out.append(
            f"Варіант {x['key']} («{x['title']}»): точність на фрагментах "
            f"{f3(x['seg_acc'])} ({pp(x['seg_acc'] - A['seg_acc'])} відносно A), на "
            f"треках {f3(x['track_acc'])} ({pp(x['track_acc'] - A['track_acc'])})."
        )
    aug = [x for x in gz["experiments"] if x["config"]["spec_augment"]]
    if aug and max(x["seg_acc"] for x in aug) > A["seg_acc"]:
        out.append(
            "На відміну від UrbanSound8K, тут аугментація SpecAugment помітно "
            "допомагає: музичні фрагменти довгі і насичені, тому затирання кількох "
            "смуг частот або проміжків часу не знищує інформацію про жанр, а лише "
            "змушує мережу спиратися на кілька ознак одночасно (ритм, тембр, "
            "гармонію). Оскільки навчальних треків лише ≈ 720, регуляризація тут "
            "особливо важлива."
        )
    return out


