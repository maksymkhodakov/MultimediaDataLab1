"""
Аналітичні тексти звіту: обговорення експериментів, помилок і висновки.

Кожна функція отримує метрики з results/*.json і повертає список абзаців.
Усі числа (точності, різниці, кількості помилок) підставляються з даних.
Інтерпретація написана за фактичними результатами навчання; там, де висновок
залежить від співвідношення результатів (допомогла зміна параметра чи ні),
формулювання обирається умовою.
"""

from config import US8K_CLASSES_UA

GENRES_UA = {
    "blues": "блюз", "classical": "класична музика", "country": "кантрі", "disco": "диско",
    "hiphop": "хіп-хоп", "jazz": "джаз", "metal": "метал", "pop": "поп",
    "reggae": "реггі", "rock": "рок",
}


def f3(x: float) -> str:
    """Число з трьома знаками після десяткової коми."""
    return f"{x:.3f}".replace(".", ",")


def pp(x: float) -> str:
    """Різниця у відсоткових пунктах зі знаком, напр. «+1,5 в. п.»."""
    return f"{100 * x:+.1f}".replace(".", ",").replace("-", "−") + " в. п."


def ua(c: str) -> str:
    """Українська назва класу або жанру."""
    return US8K_CLASSES_UA.get(c, GENRES_UA.get(c, c))


def plural(n: int, one: str, few: str, many: str) -> str:
    """Узгодження іменника з числівником: 1 кліп, 2 кліпи, 5 кліпів, 21 кліп."""
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def _effect(delta: float) -> str:
    """Словесна оцінка зміни точності (поріг 1 в. п.)."""
    if delta > 0.01:
        return f"підвищило точність ({pp(delta)})"
    if delta < -0.01:
        return f"знизило точність ({pp(delta)})"
    return f"практично не змінило точність ({pp(delta)})"


