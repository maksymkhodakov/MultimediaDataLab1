def us8k_analysis(us, e, best, by_test):
    A, B, C, D = e["A"], e["B"], e["C"], e["D"]
    out = []
    gap_a = A["final_train_acc"] - A["test_acc"]
    out.append(
        f"Базова мережа (варіант A) досягла точності {f3(A['test_acc'])} і macro-F1 "
        f"{f3(A['macro_f1'])} на тестових fold-ах. Точність на навчальній вибірці в кінці "
        f"навчання становить {f3(A['final_train_acc'])}, тобто розрив між навчанням і "
        f"тестом – {100 * gap_a:.0f} в. п.: мережа помітно перенавчається на записах "
        "навчальних fold-ів. Валідаційна точність при цьому значно нижча за тестову "
        f"({f3(A['best_val_acc'])}), що є відомою особливістю UrbanSound8K: fold-и "
        "суттєво відрізняються за складністю, тому оцінки на різних fold-ах можуть "
        "відрізнятися на 5–10 в. п."
    )
    out.append(
        f"{_effect(B['test_acc'] - A['test_acc'], 'Додавання SpecAugment (варіант B)')} "
        f"порівняно з базовою моделлю. Точність на навчальній вибірці при цьому "
        f"знизилася до {f3(B['final_train_acc'])} – аугментація ускладнює задачу "
        "навчання і зменшує перенавчання, але для маленької мережі (≈ 99 тис. "
        "параметрів) затирання частини спектрограми може забирати занадто багато "
        "інформації: короткі звуки (постріл, гавкіт, гудок) займають лише кілька "
        "кадрів і можуть бути повністю замасковані."
    )
    out.append(
        f"{_effect(C['test_acc'] - B['test_acc'], 'Збільшення кількості фільтрів удвічі (варіант C)')} "
        f"порівняно з варіантом B (macro-F1 {f3(C['macro_f1'])}). Ширша мережа має "
        "більшу ємність і краще використовує аугментовані дані, тобто SpecAugment і "
        "ширина мережі доповнюють одна одну."
    )
    out.append(
        f"{_effect(D['test_acc'] - B['test_acc'], 'Зменшення швидкості навчання до 5·10⁻⁴ (варіант D)')} "
        "порівняно з варіантом B: за 30 епох мережа з малою швидкістю навчання "
        f"не встигає збігтися (точність на навчальній вибірці лише "
        f"{f3(D['final_train_acc'])})."
    )
    if "E" in e:
        E = e["E"]
        out.append(
            f"Ширша мережа без аугментації (варіант E) показала точність {f3(E['test_acc'])} "
            f"при точності на навчанні {f3(E['final_train_acc'])}: "
            + ("без регуляризації ширша мережа ще сильніше перенавчається, і виграш від "
               "ширини менший, ніж у поєднанні з SpecAugment."
               if E["test_acc"] < C["test_acc"] else
               "навіть без аугментації ширина мережі дає приріст точності.")
        )
    if "F" in e:
        F = e["F"]
        out.append(
            f"Подовження навчання ширшої мережі з SpecAugment до {F['config']['epochs']} епох "
            f"(варіант F) дало точність {f3(F['test_acc'])} і macro-F1 {f3(F['macro_f1'])} "
            + ("– аугментовані дані дозволяють довше навчатися без перенавчання."
               if F["test_acc"] > C["test_acc"] else
               "– додаткові епохи вже не дають помітного приросту.")
        )
    if by_test["key"] != best["key"]:
        out.append(
            f"Слід зазначити, що найвищу точність на тесті має варіант {by_test['key']} "
            f"({f3(by_test['test_acc'])}), а найкращим за валідацією є варіант "
            f"{best['key']}. У роботі остаточна модель обирається саме за валідацією: "
            "вибір за тестовою вибіркою дав би оптимістично завищену оцінку, бо тест "
            "тоді фактично брав би участь у налаштуванні моделі."
        )
    return out


def us8k_confusion_analysis(us, f1_sorted):
    out = []
    worst = f1_sorted[:3]
    bestc = f1_sorted[-3:][::-1]
    out.append(
        "Найкраще розпізнаються класи "
        + ", ".join(f"«{ua(c)}» (F1 = {f3(v)})" for v, c in bestc)
        + ": у них дуже характерна форма на спектрограмі – короткий широкосмуговий "
        "імпульс пострілу, стабільні гармоніки автомобільного сигналу, плавні дуги "
        "сирени або рівномірний гул двигуна."
    )
    conf = us["top_confusions"][:4]
    out.append(
        "Найслабші класи – "
        + ", ".join(f"«{ua(c)}» (F1 = {f3(v)})" for v, c in worst)
        + ". Найчастіші помилки на тестовій вибірці: "
        + "; ".join(f"«{ua(t)}» → «{ua(p)}» ({n} кліпів)" for n, t, p in conf)
        + "."
    )
    out.append(
        "Такі помилки мають фізичне пояснення. Кондиціонер, двигун на холостому ходу, "
        "дриль і відбійний молоток – це стаціонарні механічні шуми з енергією, "
        "зосередженою в низьких і середніх частотах; їхні спектрограми – рівномірна "
        "«текстура» без чітких подій у часі, і відрізняються вони лише тонкими "
        "деталями (частотою ударів, наявністю гармонік). Дриль і відбійний молоток "
        "звучать схоже (періодичні удари або обертання), тому плутаються між собою. "
        "Дитячі ігри і вулична музика часто містять голоси, музику та фоновий "
        "вуличний шум одночасно, тому їх межі розмиті. Крім того, багато кліпів "
        "UrbanSound8K записано на фоні інших звуків (у датасеті є ознака salience – "
        "звук на передньому чи задньому плані), що ускладнює класифікацію."
    )
    return out


def my_analysis(my, n_correct):
    out = [
        f"Мережа правильно визначила клас для {n_correct} з {len(my)} записів."
    ]
    for m in my:
        top1, p1 = m["top3"][0]
        if m["correct"]:
            out.append(
                f"Запис {m['file']} (очікуваний клас «{ua(m['expected'])}») класифіковано "
                f"правильно з імовірністю {p1:.0%}"
                + (f"; окремо правильно класифіковано {m['window_hits']:.0%} вікон."
                   if m["n_windows"] > 1 else ".")
            )
        else:
            exp_p = dict(m["top3"]).get(m["expected"])
            out.append(
                f"Запис {m['file']} (очікуваний клас «{ua(m['expected'])}») віднесено до "
                f"класу «{ua(top1)}» ({p1:.0%})"
                + (f", правильний клас – серед top-3 з імовірністю {exp_p:.0%}."
                   if exp_p is not None else ", правильного класу немає серед top-3.")
            )
    out.append(
        "Помилки на «чужих» записах – очікуване явище, і вони мають кілька причин. "
        "По-перше, інший мікрофон і інша відстань до джерела змінюють спектральний "
        "баланс запису: в UrbanSound8K більшість звуків записано на вулиці здалеку, "
        "з реверберацією та фоновим шумом, а тестові записи часто зроблені зблизька. "
        "По-друге, короткий одиночний звук (гудок, гавкіт) у вікні 4 с займає малу "
        "частку часу, а решта вікна – тиша або фон, тому важливу роль відіграє фон. "
        "По-третє, класи, що плутаються на тестовій вибірці (дриль – відбійний "
        "молоток, дитячі ігри – вулична музика), так само плутаються і на нових "
        "записах. Для запису власних звуків рекомендується використовувати формат "
        "WAV (моно), вимикати шумозаглушення телефона, записувати щонайменше 4 с і "
        "уникати накладання кількох джерел звуку."
    )
    return out


