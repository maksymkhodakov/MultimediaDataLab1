def my_analysis(my, n_correct):
    out = [f"Мережа правильно визначила клас для {n_correct} з {len(my)} записів."]
    for m in my:
        top1, p1 = m["top3"][0]
        if m["correct"]:
            s = (f"Запис {m['file']} (очікуваний клас «{ua(m['expected'])}») "
                 f"класифіковано правильно з імовірністю {p1:.0%}")
            if m["n_windows"] > 1:
                s += (f"; окремо правильно класифіковано {m['window_hits']:.0%} з "
                      f"{m['n_windows']} вікон.")
            else:
                s += "."
            out.append(s)
        else:
            exp_p = dict(m["top3"]).get(m["expected"])
            out.append(
                f"Запис {m['file']} (очікуваний клас «{ua(m['expected'])}») віднесено до "
                f"класу «{ua(top1)}» ({p1:.0%})"
                + (f", правильний клас – серед top-3 з імовірністю {exp_p:.0%}."
                   if exp_p is not None else ", правильного класу немає серед top-3.")
            )
    by_file = {m["file"]: m for m in my}
    if "car_horn.wav" in by_file and not by_file["car_horn.wav"]["correct"]:
        out.append(
            "Помилку на записі автомобільного сигналу добре видно на його "
            f"спектрограмі (рисунок 6.{my.index(by_file['car_horn.wav']) + 1}): запис складається з двох коротких (≈ 0,3 с) "
            "гудків, записаних зблизька, між якими – тиша. За формою це два короткі "
            "гармонійні спалахи – саме так виглядає гавкіт собаки. У UrbanSound8K "
            "автомобільні сигнали здебільшого довші, записані здалеку на фоні "
            "вуличного шуму, тому мережа навчилась пов'язувати цей клас із довшими "
            "сигналами на шумному фоні."
        )
    dr = by_file.get("drilling_next_door.wav")
    if dr and dr["correct"]:
        out.append(
            f"Запис дрилі класифіковано правильно, але з невеликим запасом "
            f"({dr['top3'][0][1]:.0%} проти {dr['top3'][1][1]:.0%} для класу "
            f"«{ua(dr['top3'][1][0])}»): дриль у записі працює уривками, з паузами, і "
            "вікна, у які потрапляють лише короткі уривки роботи, мережа приймає за "
            "короткі події на кшталт гавкоту. Тут добре видно користь усереднення "
            "ймовірностей по вікнах: окремі вікна помиляються, а результат для "
            "всього запису правильний."
        )
    out.append(
        "Загалом помилки на «чужих» записах мають кілька причин: інший мікрофон і "
        "відстань до джерела змінюють спектральний баланс запису; короткий "
        "одиночний звук займає малу частку 4-секундного вікна; класи, що "
        "плутаються на тестовій вибірці, так само плутаються й на нових записах. "
        "Для запису власних звуків рекомендується формат WAV (моно), вимкнене "
        "шумозаглушення телефона, тривалість від 4 с і відсутність накладання "
        "кількох джерел звуку."
    )
    return out


