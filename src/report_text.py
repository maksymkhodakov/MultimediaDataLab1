"""
Аналітичні тексти звіту: обговорення експериментів, помилок і висновки.

Кожна функція отримує метрики з results/*.json і повертає список абзаців.
Числа та порівняння (що краще, на скільки) обчислюються з даних, тому тексти
залишаються правильними після повторного навчання. Формулювання, що
залежать від результату (допомогла аугментація чи ні тощо), обираються
умовами.
"""

from config import US8K_CLASSES_UA

GENRES_UA = {
    "blues": "блюз", "classical": "класична музика", "country": "кантрі", "disco": "диско",
    "hiphop": "хіп-хоп", "jazz": "джаз", "metal": "метал", "pop": "поп",
    "reggae": "реггі", "rock": "рок",
}


def f3(x: float) -> str:
    return f"{x:.3f}".replace(".", ",")


def pp(x: float) -> str:
    """Різниця у відсоткових пунктах зі знаком."""
    return f"{100 * x:+.1f}".replace(".", ",").replace("-", "−") + " в. п."


def ua(c: str) -> str:
    return US8K_CLASSES_UA.get(c, GENRES_UA.get(c, c))


def _effect(delta: float, what: str) -> str:
    """Словесна оцінка зміни точності."""
    if delta > 0.01:
        return f"{what} підвищило точність на тесті ({pp(delta)})"
    if delta < -0.01:
        return f"{what} знизило точність на тесті ({pp(delta)})"
    return f"{what} практично не змінило точність на тесті ({pp(delta)})"


