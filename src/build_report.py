def render_pdf(docx_path: Path) -> Path:
    """Перетворює .docx у PDF за допомогою LibreOffice (для підрахунку сторінок)."""
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir",
                    str(docx_path.parent), str(docx_path)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return docx_path.with_suffix(".pdf")


def find_heading_pages(pdf_path: Path, headings: list):
    """Шукає номер сторінки кожного заголовка у PDF (заголовки йдуть по порядку)."""
    import re
    text = subprocess.run(["pdftotext", "-layout", str(pdf_path), "-"], capture_output=True,
                          text=True, check=True).stdout
    pages = [re.sub(r"\s+", " ", pg) for pg in text.split("\f")]
    result, current = [], 3  # пошук починаємо після сторінки змісту
    for level, title in headings:
        # для додатка шукаємо лише «ДОДАТОК А» (назва — в окремому рядку)
        needle = re.sub(r"\s+", " ", title if not title.startswith("ДОДАТОК") else title[:9])
        for i in range(current, len(pages)):
            if needle in pages[i]:
                current = i
                break
        result.append((level, title, current + 1))
    return result, len(pages) - (1 if not pages[-1].strip() else 0)


def main():
    """Три проходи: (1) зібрати заголовки; (2) звіт зі змістом-заглушкою такої ж
    довжини — щоб визначити сторінки; (3) остаточний звіт з номерами сторінок."""
    tmp_dir = Path(tempfile.mkdtemp())
    _, headings = build(output=tmp_dir / "pass1.docx")
    draft = [(lvl, t, "00") for lvl, t in headings]
    path2, _ = build(toc_entries=draft, n_pages=99, output=tmp_dir / "pass2.docx")
    entries, n_pages = find_heading_pages(render_pdf(path2), headings)
    out, _ = build(toc_entries=entries, n_pages=n_pages)
    shutil.rmtree(tmp_dir, ignore_errors=True)
    print(f"Звіт збережено: {out} ({n_pages} с.)")


