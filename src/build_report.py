def load(name: str):
    with open(RESULTS_DIR / name, encoding="utf-8") as f:
        return json.load(f)


def f3(x: float) -> str:
    """Число з трьома знаками після коми через десяткову кому (як прийнято в Україні)."""
    return f"{x:.3f}".replace(".", ",")


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}".replace(".", ",") + " %"


def ua(cls: str) -> str:
    return US8K_CLASSES_UA.get(cls, GENRES_UA.get(cls, cls))


def lr_str(lr: float) -> str:
    return f"{lr:.0e}".replace("e-0", "·10⁻").replace("e-", "·10⁻")


